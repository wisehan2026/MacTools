import AppKit
import Combine
import CryptoKit

/// 剪贴板历史的唯一状态入口：主线程轮询系统剪贴板，管理去重、收藏、过期清理与磁盘索引。
@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()
    @Published private(set) var entries: [ClipboardEntry] = []
    @Published var paused = false
    @Published var message: String?
    // 从当前版本开始观察，不在启动时自动收录启动前已经存在的剪贴板内容。
    private var changeCount: Int
    private let board: NSPasteboard
    private let directory: URL
    private var timer: Timer?
    private var monitoringRequested = false
    private var featureEnabled: Bool
    private var lastCleanup = Date.distantPast
    private var subscriptions: Set<AnyCancellable> = []
    private let settings: SettingsStore

    init(directory: URL = LocalFiles.clipboard, board: NSPasteboard = .general, settings: SettingsStore = .shared) {
        self.directory = directory
        self.board = board
        self.settings = settings
        featureEnabled = settings.isEnabled(.clipboard)
        changeCount = board.changeCount
        do {
            try LocalFiles.ensure(directory)
            let manifest = directory.appendingPathComponent("history.json")
            if FileManager.default.fileExists(atPath: manifest.path) {
                entries = try JSONDecoder().decode([ClipboardEntry].self, from: Data(contentsOf: manifest))
            }
            // 启动时也执行清理，让应用关闭期间已经过期的记录及时失效。
            clean()
        } catch { message = "读取历史失败，原文件已保留：\(error.localizedDescription)" }
        // @Published 在属性写入前发送变化；排入主线程任务后再读取设置，确保使用更新后的值。
        settings.$retentionDays.dropFirst().sink { [weak self] _ in Task { @MainActor in self?.clean() } }.store(in: &subscriptions)
        settings.$capacityMB.dropFirst().sink { [weak self] _ in Task { @MainActor in self?.clean() } }.store(in: &subscriptions)
        settings.$disabledFeatures.dropFirst().sink { [weak self] _ in Task { @MainActor in self?.synchronizeFeatureState() } }.store(in: &subscriptions)
    }

    /// 以较低频率检测 changeCount，只有剪贴板变化时才读取和转换内容。
    func start() {
        monitoringRequested = true
        synchronizeFeatureState()
    }

    func synchronizeFeatureState() {
        let enabled = settings.isEnabled(.clipboard)
        if featureEnabled != enabled { changeCount = board.changeCount; featureEnabled = enabled }
        if !enabled { timer?.invalidate(); timer = nil; return }
        guard monitoringRequested, timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.65, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    func poll() {
        synchronizeFeatureState()
        guard featureEnabled else { changeCount = board.changeCount; return }
        // 清理与复制事件无关：即使用户没有复制，也要处理跨天过期。
        if Date().timeIntervalSince(lastCleanup) > 60 { clean(); lastCleanup = Date() }
        guard board.changeCount != changeCount else { return }
        // 暂停或排除期间仍推进版本号，恢复记录后不会补录本次被跳过的内容。
        changeCount = board.changeCount
        guard !paused else { return }
        // 系统剪贴板不直接提供可靠的来源进程，这里以前台应用作近似识别。
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? "未知应用"
        let excluded = settings.excludedApps.components(separatedBy: .newlines).map { $0.trimmingCharacters(in: .whitespaces) }
        guard !excluded.contains(source) else { return }
        // 尊重来源应用声明的保密、临时及自动生成标记；不能据此识别所有敏感文本。
        let sensitive = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !sensitive.contains(where: { board.types?.contains(NSPasteboard.PasteboardType($0)) == true }) else { return }
        do {
            // 同一条剪贴板可能提供多种表示，优先保留图片；没有可读图片时再读取纯文字。
            if let type = MemeMedia.originalTypes.first(where: { board.types?.contains($0) == true }),
               let data = board.data(forType: type), let media = try? MemeMedia(data: data) {
                let title = board.string(forType: MemeMedia.marker)
                try insert(data: media.data, text: nil, source: source, ext: media.fileExtension, memeTitle: title)
            } else if board.canReadObject(forClasses: [NSImage.self], options: nil),
               let image = (board.readObjects(forClasses: [NSImage.self]) as? [NSImage])?.first,
               let cg = image.cgImage(forProposedRect: nil, context: nil, hints: nil) {
                try insert(data: LocalFiles.png(cg), text: nil, source: source)
            } else if let text = board.string(forType: .string), !text.isEmpty {
                try insert(data: Data(text.utf8), text: text, source: source)
            }
        } catch { message = error.localizedDescription }
    }

    /// 以原始字节去重；已归类的表情不会在普通复制时退回“图片”。先提交索引再清理旧文件。
    @discardableResult
    private func insert(data: Data, text: String?, source: String, ext: String = "png", memeTitle: String? = nil) throws -> Bool {
        let capacity = Int64(settings.capacityMB) * 1_024 * 1_024
        let hash = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
        let favorites = entries.filter { $0.favorite && $0.fingerprint != hash }.reduce(Int64(0)) { $0 + $1.bytes }
        guard Int64(data.count) + favorites <= capacity else {
            message = "容量不足：请增加上限或清理收藏。本次内容未记录。"
            return false
        }
        var updated = entries
        var newFile: URL?
        if let index = updated.firstIndex(where: { $0.fingerprint == hash }) {
            updated[index].createdAt = Date()
            updated[index].source = source
            if let memeTitle { updated[index].kind = .meme; updated[index].memeTitle = memeTitle }
        } else {
            var entry = ClipboardEntry(createdAt: Date(), kind: text == nil ? .image : .text, text: text, fingerprint: hash, source: source, bytes: Int64(data.count))
            if let memeTitle { entry.kind = .meme; entry.memeTitle = memeTitle }
            if text == nil {
                let folder = directory.appendingPathComponent(LocalFiles.day(entry.createdAt), isDirectory: true)
                try LocalFiles.ensure(folder)
                let file = folder.appendingPathComponent("\(entry.id).\(ext)")
                try data.write(to: file, options: .atomic)
                newFile = file
                entry.imagePath = file.path.replacingOccurrences(of: directory.path + "/", with: "")
            }
            updated.insert(entry, at: 0)
        }
        let retained = ClipboardPolicy.retained(updated, days: settings.retentionDays, capacity: capacity)
        do {
            try JSONEncoder().encode(retained).write(to: directory.appendingPathComponent("history.json"), options: .atomic)
        } catch {
            if let newFile { try? FileManager.default.removeItem(at: newFile) }
            throw error
        }
        let ids = Set(retained.map(\.id))
        removeFiles(entries.filter { !ids.contains($0.id) })
        entries = retained
        return true
    }

    /// 用户主动双击属于明确保存操作，即使暂停自动监听也收录；写入后推进版本，避免轮询重复收录。
    func copyMeme(_ media: MemeMedia, title: String, source: String = "memecub") throws -> String {
        let item = try media.pasteboardItem(title: title)
        var saved = false
        var failure: String?
        if settings.isEnabled(.clipboard) {
            do { saved = try insert(data: media.data, text: nil, source: source, ext: media.fileExtension, memeTitle: title) }
            catch { failure = "历史保存失败：\(error.localizedDescription)" }
        } else { failure = "剪贴板历史功能已关闭，未记录" }
        board.clearContents()
        guard board.writeObjects([item]) else { throw AppFailure.message("写入系统剪贴板失败，请重试") }
        changeCount = board.changeCount
        let result = saved ? "已复制，并保存到剪贴板历史的「表情包」分类" : "已复制；" + (failure ?? message ?? "本次未保存到历史")
        message = result
        return result
    }

    func imageURL(_ entry: ClipboardEntry) -> URL? {
        entry.imagePath.map { directory.appendingPathComponent($0) }
    }

    /// 只写入系统剪贴板；不会模拟粘贴，用户仍在目标应用中使用 ⌘V。
    func copy(_ entry: ClipboardEntry) {
        if entry.kind == .text, let text = entry.text {
            board.clearContents(); board.setString(text, forType: .string)
        } else if let url = imageURL(entry) {
            do {
                let media = try MemeMedia(data: Data(contentsOf: url), limitRemoteImage: false)
                let item = try media.pasteboardItem(title: entry.kind == .meme ? entry.memeTitle ?? "表情包" : nil)
                board.clearContents()
                guard board.writeObjects([item]) else { throw AppFailure.message("写入剪贴板失败") }
            } catch { message = "图片复制失败：\(error.localizedDescription)"; return }
        } else { message = "图片文件不可用"; return }
        // 跳过本次由历史窗口发起的写入，避免自身轮询再次收录并刷新记录日期。
        changeCount = board.changeCount
        message = "已复制，切回目标应用后按 ⌘V 粘贴"
    }

    func toggleFavorite(_ entry: ClipboardEntry) {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[index].favorite.toggle()
        persist()
    }

    func delete(_ entry: ClipboardEntry) { removeFiles([entry]); entries.removeAll { $0.id == entry.id }; persist() }
    func clearUnpinned() { let removed = entries.filter { !$0.favorite }; removeFiles(removed); entries.removeAll { !$0.favorite }; persist() }

    /// 纯策略先算出保留集合，再删除淘汰条目的图片并更新索引。
    func clean() {
        let retained = ClipboardPolicy.retained(entries, days: settings.retentionDays, capacity: Int64(settings.capacityMB) * 1_024 * 1_024)
        let ids = Set(retained.map(\.id))
        removeFiles(entries.filter { !ids.contains($0.id) })
        entries = retained
        persist()
    }

    private func removeFiles(_ removed: [ClipboardEntry]) {
        for entry in removed {
            if let url = imageURL(entry) {
                do { try FileManager.default.removeItem(at: url) }
                catch { if FileManager.default.fileExists(atPath: url.path) { message = "清理图片失败：\(error.localizedDescription)" } }
            }
        }
    }

    /// 原子替换 JSON，减少进程中断时留下半份索引的风险；图片文件的写入另行完成。
    private func persist() {
        do {
            try JSONEncoder().encode(entries).write(to: directory.appendingPathComponent("history.json"), options: .atomic)
        } catch { message = "保存历史失败：\(error.localizedDescription)" }
    }
}
